import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,copyFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {Store} from '../server/store.mjs';
import {JudgeService} from '../server/service.mjs';
import {WorkspaceService} from '../server/workspaces.mjs';
import {ProductionService} from '../server/production.mjs';
import {AdvancedService} from '../server/advanced.mjs';
import {GovernanceService} from '../server/governance.mjs';
import {RevisionService} from '../server/revisions.mjs';
import {MetricsImportService} from '../server/metrics-import.mjs';
import {ReadinessService} from '../server/ops25.mjs';
import {IdentityService} from '../server/identity.mjs';
const legacy=resolve('tests/fixtures/v025.sqlite');
test('real JUDGE 0.25 SQLite schema 22 migrates to schema 27 and preserves owner, case, release and permissions',t=>{
 const dir=mkdtempSync(join(tmpdir(),'judge-migrate-v025-'));t.after(()=>rmSync(dir,{recursive:true,force:true}));const copy=join(dir,'legacy.sqlite');copyFileSync(legacy,copy);
 const db=new Store(copy);t.after(()=>db.close());
 assert.equal(db.one('PRAGMA user_version').user_version,28);
 assert.equal(db.one('PRAGMA quick_check').quick_check,'ok');
 assert.equal(db.all('PRAGMA foreign_key_check').length,0);
 assert.equal(db.one('SELECT COUNT(*) AS n FROM cases').n,1);
 assert.equal(db.one('SELECT COUNT(*) AS n FROM campaign_releases').n,1);
 assert.equal(db.one('SELECT COUNT(*) AS n FROM workspace_members').n,2);
 const j=new JudgeService(db),ws=new WorkspaceService(j),prod=new ProductionService(j,ws),adv=new AdvancedService(prod,j),gov=new GovernanceService(prod,adv);
 prod.advanced=adv;prod.governance=gov;adv.governance=gov;
 const release=db.one('SELECT * FROM campaign_releases');
 assert.equal(prod.exportRelease('migration-owner',release.campaign_id,release.id).sha256,release.digest);
 assert.equal(prod.detail('migration-owner',release.campaign_id).campaign.status,'approved');
 db.run('INSERT INTO users VALUES(?,?,?,?)','nonowner','intruder@qa.invalid','none','2026-10-22T05:00:00Z');
 assert.throws(()=>prod.exportRelease('nonowner',release.campaign_id,release.id),e=>e.code==='NOT_FOUND');
 assert.equal(new RevisionService(prod).compare('migration-owner',release.campaign_id,release.id).canRestore,true);
 assert.equal(new MetricsImportService(adv).list('migration-owner',release.campaign_id).length,0);
 const report=new ReadinessService({store:db,judge:j,identity:new IdentityService(db)}).report();
 assert.equal(report.productionReady,false);assert.ok(report.blockers.includes('durable_server_database'));
 assert.equal(db.one('SELECT COUNT(*) AS n FROM delivery_queue').n,0);
});
