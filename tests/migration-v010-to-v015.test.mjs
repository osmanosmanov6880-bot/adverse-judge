import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {mkdtempSync,copyFileSync,rmSync} from 'node:fs';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {tmpdir} from 'node:os';
import {Store} from '../server/store.mjs';
import {JudgeService} from '../server/service.mjs';
import {WorkspaceService} from '../server/workspaces.mjs';
import {ResearchService} from '../server/research.mjs';
import {ProductionService} from '../server/production.mjs';
import {verifyDatabase} from '../scripts/verify-db.mjs';
const key='ADVERSE_JUDGE_TEST_MIGRATION_LEDGER_KEY_ONLY_2026';
const dir=dirname(fileURLToPath(import.meta.url));
const from=join(dir,'fixtures/v010.sqlite');
const owner='a8d431c2-1276-4d10-8e5b-b1bfca521244';
const reviewer='19a44d6c-8f39-40bb-a17d-735e9f33c9e2';
const caseId='24caff92-549c-4582-b93b-f3b69d8fd3f2';
test('real v0.10 schema v7 fixture upgrades to v0.15 schema v12 without losing cases, votes, studies or workspace',t=>{
 const temp=mkdtempSync(join(tmpdir(),'judge-upgrade-v010-v015-'));
 t.after(()=>rmSync(temp,{recursive:true,force:true}));
 const file=join(temp,'data.sqlite');copyFileSync(from,file);
 // v0.10 is signed. Production requires the same ledger key during upgrade.
 const store=new Store(file,{ledgerSecret:key});t.after(()=>store.close());
 assert.equal(store.one('PRAGMA user_version').user_version,28);
 assert.equal(store.one('SELECT COUNT(*) n FROM cases').n,1);
 assert.equal(store.one('SELECT COUNT(*) n FROM events').n,8);
 assert.equal(store.one('SELECT COUNT(*) n FROM comparison_votes').n,1);
 assert.equal(store.one('SELECT COUNT(*) n FROM research_studies').n,1);
 assert.equal(store.one('SELECT COUNT(*) n FROM workspace_members').n,2);
 assert.equal(store.one('SELECT COUNT(*) n FROM sessions').n,1);
 assert.equal(store.one('SELECT COUNT(*) n FROM campaigns').n,0);
 const judge=new JudgeService(store);assert.equal(judge.audit(owner,caseId).consistent,true);
 const ws=new WorkspaceService(judge),production=new ProductionService(judge,ws);
 const wid=ws.list(owner)[0].id;
 assert.equal(ws.detail(reviewer,wid).cases.length,1);
 assert.equal(new ResearchService(judge).list(owner).length,1);
 const campaign=production.create(owner,{workspaceId:wid,name:'Upgraded team campaign',objective:'Verify old data and new application flow',audience:'Small business operators',channel:'social'});
 assert.equal(campaign.campaign.revision,1);
 assert.equal(production.list(reviewer,wid).length,1);
 const integrity=store.one('PRAGMA foreign_key_check');assert.equal(integrity,undefined);
 assert.equal(store.auditLedger(caseId).consistent,true);
});
test('real v0.10 HMAC ledger rejects incorrect key before upgrading to v0.15',t=>{
 const temp=mkdtempSync(join(tmpdir(),'judge-wrong-key-'));
 t.after(()=>rmSync(temp,{recursive:true,force:true}));
 const file=join(temp,'legacy.sqlite');copyFileSync(from,file);
 assert.throws(()=>new Store(file,{ledgerSecret:'WRONG_TEST_KEY_0123456789_ABCDEFGHIJKLMNOPQRSTUVWXYZ'}),/Ledger key or algorithm mismatch/);
});
